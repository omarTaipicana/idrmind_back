const express=require('express');
const multer=require('multer');
const path=require('path');
const fs=require('fs');
const crypto=require('crypto');
const verifyJWT=require('../utils/verifyJWT');
const c=require('../controllers/affiliates.controllers');
const router=express.Router();
const folder=path.join(__dirname,'../../private_storage/affiliate_documents');fs.mkdirSync(folder,{recursive:true,mode:0o700});
const upload=multer({storage:multer.diskStorage({destination:folder,filename:(req,file,cb)=>cb(null,crypto.randomUUID()+'.bin')}),limits:{fileSize:10*1024*1024,files:1},fileFilter:(req,file,cb)=>cb(null,['application/pdf','image/jpeg','image/png','application/xml','text/xml'].includes(file.mimetype))});
const hits=new Map();function limit(req,res,next){const now=Date.now(),key=req.ip;let hit=hits.get(key);if(!hit||now>hit.until){hit={count:0,until:now+60000};hits.set(key,hit);}if(hits.size>10000)hits.delete(hits.keys().next().value);if(++hit.count>120)return res.status(429).json({message:'Demasiadas solicitudes.'});next();}
router.post('/affiliates/referral',limit,c.referral);
router.get('/affiliates/invitation/:code',limit,c.invitation);
router.use('/affiliates',verifyJWT);
router.get('/affiliates/me',c.me);
router.post('/affiliates/apply',c.apply);
router.put('/affiliates/me',c.updateProfile);
router.post('/affiliates/files',limit,upload.single('file'),c.upload);
router.get('/affiliates/files/:id',c.file);
router.post('/affiliates/payouts/:id/invoice',c.invoice);
router.get('/affiliates/admin',c.admin,c.adminList);
router.get('/affiliates/admin/users',c.admin,c.users);
router.post('/affiliates/admin/applications',c.admin,c.adminAdd);
router.post('/affiliates/admin/profiles/:id',c.admin,c.review);
router.put('/affiliates/admin/settings',c.admin,(req,res,next)=>require('../utils/sessionSecurity').isSuperAdmin(req.user)?next():res.sendStatus(403),c.config);
router.post('/affiliates/admin/close',c.admin,c.close);
router.post('/affiliates/admin/payouts/:id/:action',c.admin,c.payout);
router.get('/affiliates/admin/refunds',c.admin,c.refundList);
router.post('/affiliates/admin/payments/:id/refunds',c.admin,c.requestRefund);
router.post('/affiliates/admin/refunds/:id/:action',c.admin,c.transitionRefund);
module.exports=router;
